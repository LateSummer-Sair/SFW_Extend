package sair.v4.ctx;

/** 输出落点：把一句话送到"当前会话"（本地控制台 / QQ 群 / QQ 私聊）。 */
public interface Sink {

    /** 会话最终输出（整段）。 */
    void say(String text);

    /** 流式增量（可为 null 表示不支持流式）。 */
    void stream(String delta);

    /** 过程/诊断信息（只进控制台，不进 QQ）。 */
    void notice(String text);

    /**
     * 这个落点是不是<b>投递通路</b>（定时/后台任务的落点：{@code Sinks.TaskSink}）——
     * 是的话返回目标会话键（{@code group:<群号>} / {@code qq:<QQ>}），否则返回 {@code null}（默认）。
     *
     * <p><b>为什么要这一口</b>：投递通路的落点会把<b>本回合的正文直接发到目标会话</b>（这就是"到点她自己
     * 说一句"）。正文会被发出去的回合，和她"写给自己看"的回合，内容纪律不一样 —— 前者只该写
     * "对用户说的话"，不能写回执/汇报腔（2026-09-15 真机事故：定时那一轮的正文被投递进群，
     * 内容是"已经查了并回群里了…得跟你说清"这种回执）。基板在这里只回答"落点是什么"这个事实，
     * 纪律文案由 {@code Agent.ask} 注入。</p>
     *
     * <p>默认 {@code null} = 普通会话落点（网关/控制台的回复）：正文就是回复本身，不需要额外纪律；
     * 老落点实现（含探针里的记录器）一个字都不用改。</p>
     */
    default String deliverTo() { return null; }
}
